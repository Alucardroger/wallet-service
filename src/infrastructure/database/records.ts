import { defineEntity, p, type InferEntity } from '@mikro-orm/postgresql';

/**
 * Persistence records: one per table, plain data only. The domain classes do
 * not know about these; the adapter converts between the two.
 * Money is NUMERIC(20,2) in the database and a decimal string here, never a number.
 */
const money = () => p.decimal('string').columnType('numeric(20,2)');

export const WalletRecord = defineEntity({
  name: 'WalletRecord',
  tableName: 'wallets',
  properties: {
    id: p.uuid().primary(),
    playerId: p.string(),
    currency: p.string(),
    balance: money(),
    version: p.integer(),
    createdAt: p.datetime(),
    updatedAt: p.datetime(),
  },
});
export type WalletRecord = InferEntity<typeof WalletRecord>;

export const WagerTransactionRecord = defineEntity({
  name: 'WagerTransactionRecord',
  tableName: 'wager_transactions',
  properties: {
    id: p.uuid().primary(),
    providerId: p.string(),
    externalTransactionId: p.string(),
    idempotencyKey: p.string(),
    payloadHash: p.string(),
    walletId: p.uuid(),
    playerId: p.string(),
    roundId: p.string(),
    gameId: p.string(),
    kind: p.string(),
    amount: money(),
    currency: p.string(),
    referenceExternalTransactionId: p.string().nullable(),
    referenceTransactionId: p.uuid().nullable(),
    status: p.string(),
    failureCode: p.string().nullable(),
    resultBalance: money().nullable(),
    referenceAttempts: p.integer(),
    nextReferenceAttemptAt: p.datetime().nullable(),
    correlationId: p.string().nullable(),
    createdAt: p.datetime(),
    processedAt: p.datetime().nullable(),
  },
});
export type WagerTransactionRecord = InferEntity<typeof WagerTransactionRecord>;

/** `seq` is generated by the database and only read through SQL (ledger cursor). */
export const LedgerEntryRecord = defineEntity({
  name: 'LedgerEntryRecord',
  tableName: 'wallet_ledger_entries',
  properties: {
    id: p.uuid().primary(),
    walletId: p.uuid(),
    transactionId: p.uuid(),
    direction: p.string(),
    amount: money(),
    currency: p.string(),
    balanceBefore: money(),
    balanceAfter: money(),
    createdAt: p.datetime(),
  },
});
export type LedgerEntryRecord = InferEntity<typeof LedgerEntryRecord>;

export const OutboxRecord = defineEntity({
  name: 'OutboxRecord',
  tableName: 'outbox_messages',
  properties: {
    id: p.uuid().primary(),
    aggregateId: p.string(),
    eventType: p.string(),
    payload: p.json<Record<string, unknown>>(),
    occurredAt: p.datetime(),
    attempts: p.integer(),
    nextAttemptAt: p.datetime().nullable(),
    publishedAt: p.datetime().nullable(),
  },
});
export type OutboxRecord = InferEntity<typeof OutboxRecord>;

export const records = [WalletRecord, WagerTransactionRecord, LedgerEntryRecord, OutboxRecord];
